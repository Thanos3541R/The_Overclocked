STAT_NAMES = ["mean", "std", "min", "max", "median", "p10", "p90"]

LABEL_SOBER_ALIASES = {"sober", "normal", "baseline", "alert", "control", "0", "false", ""}
LABEL_IMPAIRED_ALIASES = {"impaired", "intoxicated", "alcohol", "drunk", "drowsy", "1", "true", "positive"}


def compute_subject_invariant_delta_features(
    features_2d: np.ndarray,
    flat_names: List[str],
    subjects: np.ndarray,
) -> Tuple[np.ndarray, List[str]]:
    """Convert subject-dependent physical baseline features (e.g. raw EAR) into
    subject-invariant baseline delta features relative to each subject's personal baseline.

    This prevents GroupKFold models from overfitting to individual anatomical eye aperture
    variations (e.g., naturally small eyes vs true ptosis droop), ensuring generalized
    cross-subject impairment detection.
    """
    clean_features = features_2d.copy()
    clean_names = list(flat_names)

    if len(features_2d) == 0 or len(subjects) == 0:
        return clean_features, clean_names

    unique_subs = np.unique(subjects)
    for s in unique_subs:
        mask = (subjects == s)
        if not np.any(mask):
            continue
        for col_idx, col_name in enumerate(flat_names):
            if col_name.startswith("ear_") and any(stat in col_name for stat in ["mean", "median", "min", "max", "p10", "p90"]):
                vals = features_2d[mask, col_idx]
                if len(vals) == 0 or np.all(np.isnan(vals)):
                    s_base = 0.0
                else:
                    s_base = float(np.nanpercentile(vals, 90))
                clean_features[mask, col_idx] = features_2d[mask, col_idx] - s_base
                clean_names[col_idx] = f"{col_name}_delta_base"

    return clean_features, clean_names


def compute_window_summary_features(
    windows_3d: np.ndarray,
    feature_names: List[str],
    subjects: Optional[np.ndarray] = None,
    apply_subject_deltas: bool = False,
    valid_masks: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, List[str]]:
    """Transform 3D window tensors (N, window_frames, n_features) into 2D summary statistics.

    Computes 7 statistics along the temporal axis for each feature:
      [mean, std, min, max, median, 10th percentile, 90th percentile]
    yielding N x (n_features * 7) flattened tabular features.
    If apply_subject_deltas is True and subjects array is provided, converts anatomical
    features into subject-invariant baseline deltas.
    """
    n_windows, window_frames, n_features = windows_3d.shape

    clean_3d = np.array(windows_3d, dtype=np.float32, copy=True)

    if valid_masks is None:
        # Infer timestamps > 0 & face_valid for legacy archives
        if "face_valid" in feature_names:
            fv_idx = feature_names.index("face_valid")
            valid_masks = (windows_3d[:, :, fv_idx] > 0.5)
            if "timestamp" in feature_names:
                ts_idx = feature_names.index("timestamp")
                valid_masks = valid_masks & (windows_3d[:, :, ts_idx] > 0)
        else:
            valid_masks = np.ones((n_windows, window_frames), dtype=bool)
    else:
        valid_masks = np.asarray(valid_masks, dtype=bool)

    # Set invalid/padded rows (~valid_mask) to np.nan
    clean_3d[~valid_masks] = np.nan

    # Set facial_flushing_ratio/flushing_delta to np.nan on rows where flushing_valid < 0.5
    if "flushing_valid" in feature_names:
        fv_idx = feature_names.index("flushing_valid")
        invalid_flush = (windows_3d[:, :, fv_idx] < 0.5)
        for flush_name in ["facial_flushing_ratio", "flushing_delta"]:
            if flush_name in feature_names:
                idx = feature_names.index(flush_name)
                clean_3d[invalid_flush, idx] = np.nan

    # Set rppg_pulse_bpm/rppg_hrv_rmssd_ms to np.nan on rows where rppg_valid < 0.5
    if "rppg_valid" in feature_names:
        rv_idx = feature_names.index("rppg_valid")
        invalid_rppg = (windows_3d[:, :, rv_idx] < 0.5)
        for rppg_name in ["rppg_pulse_bpm", "rppg_hrv_rmssd_ms"]:
            if rppg_name in feature_names:
                idx = feature_names.index(rppg_name)
                clean_3d[invalid_rppg, idx] = np.nan

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=RuntimeWarning)
        means = np.nanmean(clean_3d, axis=1)
        stds = np.nanstd(clean_3d, axis=1)
        mins = np.nanmin(clean_3d, axis=1)
        maxs = np.nanmax(clean_3d, axis=1)
        q10_50_90 = np.nanpercentile(clean_3d, [10.0, 50.0, 90.0], axis=1)
        p10s = q10_50_90[0]
        medians = q10_50_90[1]
        p90s = q10_50_90[2]

    means = np.nan_to_num(means, nan=0.0)
    stds = np.nan_to_num(stds, nan=0.0)
    mins = np.nan_to_num(mins, nan=0.0)
    maxs = np.nan_to_num(maxs, nan=0.0)
    medians = np.nan_to_num(medians, nan=0.0)
    p10s = np.nan_to_num(p10s, nan=0.0)
    p90s = np.nan_to_num(p90s, nan=0.0)

    # Concatenate statistics horizontally
    features_2d = np.hstack([means, stds, mins, maxs, medians, p10s, p90s]).astype(np.float32)

    # Construct feature column names
    flat_names = []
    for stat in STAT_NAMES:
        for fname in feature_names:
            flat_names.append(f"{fname}_{stat}")

    # Compute within-window self-normalizing kinetic & aperture features
    extra_cols = []
    extra_names = []

    p90_name = "ear_avg_p90" if "ear_avg_p90" in flat_names else ("ear_left_p90" if "ear_left_p90" in flat_names else None)
    p10_name = "ear_avg_p10" if "ear_avg_p10" in flat_names else ("ear_left_p10" if "ear_left_p10" in flat_names else None)
    mean_name = "ear_avg_mean" if "ear_avg_mean" in flat_names else ("ear_left_mean" if "ear_left_mean" in flat_names else None)

    if p90_name and p10_name:
        p90_idx = flat_names.index(p90_name)
        p10_idx = flat_names.index(p10_name)
        ear_aperture_range = (features_2d[:, p90_idx] - features_2d[:, p10_idx]).astype(np.float32)
        extra_cols.append(ear_aperture_range[:, None])
        extra_names.append("ear_aperture_range")

    if mean_name and p90_name:
        mean_idx = flat_names.index(mean_name)
        p90_idx = flat_names.index(p90_name)
        ear_norm_mean = (features_2d[:, mean_idx] / np.maximum(features_2d[:, p90_idx], 0.15)).astype(np.float32)
        extra_cols.append(ear_norm_mean[:, None])
        extra_names.append("ear_normalized_mean")

    open_name = "blink_opening_velocity_mean" if "blink_opening_velocity_mean" in flat_names else None
    close_name = "blink_closing_velocity_mean" if "blink_closing_velocity_mean" in flat_names else None
    if open_name and close_name:
        open_idx = flat_names.index(open_name)
        close_idx = flat_names.index(close_name)
        blink_ratio = (features_2d[:, open_idx] / np.maximum(features_2d[:, close_idx], 0.10)).astype(np.float32)
        extra_cols.append(blink_ratio[:, None])
        extra_names.append("blink_up_to_down_ratio")

    # Compute window-level ocular eyeball micro-flutter frequency (eyeball_tremor_hz_window)
    # from horizontal conjugate iris coordinates on valid non-blink, non-saccade frames
    if "left_iris_x" in feature_names and "right_iris_x" in feature_names:
        lx_idx = feature_names.index("left_iris_x")
        rx_idx = feature_names.index("right_iris_x")
        avg_ix = 0.5 * (clean_3d[:, :, lx_idx] + clean_3d[:, :, rx_idx])
        open_mask = valid_masks.copy()
        if "blink_detected" in feature_names:
            open_mask = open_mask & (windows_3d[:, :, feature_names.index("blink_detected")] < 0.5)
        if "saccade_detected" in feature_names:
            open_mask = open_mask & (windows_3d[:, :, feature_names.index("saccade_detected")] < 0.5)
        eyeball_tremor_col = np.zeros((n_windows, 1), dtype=np.float32)
        if window_frames >= 12:
            diffs = np.diff(avg_ix, axis=1)
            pair_open = open_mask[:, :-1] & open_mask[:, 1:] & np.isfinite(diffs)
            valid_diff = pair_open & (np.abs(diffs) > 0.001) & (np.abs(diffs) < 0.045)
            adj_valid = valid_diff[:, :-1] & valid_diff[:, 1:]
            signs = np.sign(diffs)
            reversals = np.sum(adj_valid & ((signs[:, :-1] * signs[:, 1:]) < 0), axis=1)
            n_val_diffs = np.sum(valid_diff, axis=1)
            est_dur_s = np.maximum(window_frames / 30.0, 0.4)
            hz = np.where(n_val_diffs >= 6, reversals / (2.0 * est_dur_s), 0.0)
            eyeball_tremor_col[:, 0] = np.round(hz, 2).astype(np.float32)
        extra_cols.append(eyeball_tremor_col)
        extra_names.append("eyeball_tremor_hz_window")

    if extra_cols:
        features_2d = np.hstack([features_2d] + extra_cols).astype(np.float32)
        flat_names.extend(extra_names)

    if apply_subject_deltas and subjects is not None:
        features_2d, flat_names = compute_subject_invariant_delta_features(
            features_2d, flat_names, subjects
        )

    return features_2d, flat_names


def filter_involuntary_features(
    X_2d: np.ndarray,
    feature_names: List[str]
) -> Tuple[np.ndarray, List[str]]:
    """Filter 2D feature matrix to retain only involuntary micromotions and autonomic signals.

    Excludes raw voluntary/posture shortcut columns (head_yaw_*, head_pitch_*, head_roll_*,
    mar_*, left_iris_x_*, left_iris_y_*, right_iris_x_*, right_iris_y_*, imu_gated_*, and
    static room color temperature facial_flushing_ratio_*), retaining only head tremor/instability
    (head_yaw_std, head_pitch_std, head_roll_std), vasodilation change (facial_flushing_ratio_std,
    flushing_delta_*), and all involuntary oculomotor/autonomic features.
    """
    keep_indices = []
    keep_names = []

    for idx, name in enumerate(feature_names):
        # Retain head instability/tremor standard deviation and vasodilation fluctuation
        if name in ("head_yaw_std", "head_pitch_std", "head_roll_std", "facial_flushing_ratio_std"):
            keep_indices.append(idx)
            keep_names.append(name)
            continue

        # Exclude other head pose statistics (voluntary head positions)
        if name.startswith(("head_yaw_", "head_pitch_", "head_roll_")):
            continue

        # Exclude voluntary mouth movements (speech, yawns)
        if name.startswith("mar_") or name.startswith("yawn_"):
            continue

        # Exclude voluntary gaze coordinates
        if name.startswith(("left_iris_x_", "left_iris_y_", "right_iris_x_", "right_iris_y_")):
            continue

        # Exclude gating mask shortcut
        if name.startswith("imu_gated_"):
            continue

        # Exclude static room color temperature (keeping facial_flushing_ratio_std and flushing_delta_*)
        if name.startswith("facial_flushing_ratio_"):
            continue

        # Exclude Section B voluntary/gaming and validity-mask prefixes when involuntary-only is active
        if name.startswith((
            "deliberate_blink_suppression_",
            "voluntary_eye_widening_",
            "stare_fixation_duration_s_",
            "compensatory_stare_active_",
            "rigid_head_stabilization_",
            "frontalis_compensation_active_",
            "brow_eye_distance_ratio_",
            "brow_elevation_delta_",
            "flushing_valid_",
            "rppg_valid_",
        )):
            continue

        keep_indices.append(idx)
        keep_names.append(name)

    return X_2d[:, keep_indices], keep_names


def load_dataset_from_npz(
    npz_paths: List[str],
    target_frames: Optional[int] = None,
    clean_contaminated: bool = True,
    return_valid_masks: bool = False,
) -> Union[Tuple[np.ndarray, np.ndarray, np.ndarray, List[str]], Tuple[np.ndarray, np.ndarray, np.ndarray, List[str], np.ndarray]]:
    """Load and concatenate training windows from multiple .npz archives.

    Handles heterogeneous archives with:
      - Channel dimension differences (29 core vs 48 extended features)
      - Temporal window frame differences due to variable camera FPS (e.g. 71, 75, 89, 90 frames)
    """
    raw_archives = []
    target_feature_names = []

    contaminated_terms = [
        "MY DRUNK GIRLFRIEND",
        "My Drunk Girlfriend",
        "MY DRUNK BLOOPERS",
        "Adults Get Drunk For The First Time",
    ]
    excluded_count = 0
    clean_paths = []

    for path in npz_paths:
        fname = os.path.basename(path)
        if clean_contaminated and fname.startswith("sober_"):
            is_contaminated = (
                any(term.lower() in fname.lower() for term in contaminated_terms)
                or ("(1)" in fname)
            )
            if is_contaminated:
                excluded_count += 1
                continue
        clean_paths.append(path)

    if clean_contaminated and excluded_count > 0:
        print(f"[Dataset Quarantine] Excluded {excluded_count} contaminated ('Drunk-in-Sober') or duplicate '(1)' archives.")

    for path in clean_paths:
        data = np.load(path, allow_pickle=True)
        feats = data["features"]  # (n_windows, window_frames, n_features)
        subs = data["subject_ids"]
        labs = data["labels"]
        fnames = list(data["feature_names"]) if "feature_names" in data else [f"feat_{i}" for i in range(feats.shape[2])]

        if "valid_masks" in data:
            vm = np.asarray(data["valid_masks"], dtype=bool)
        else:
            # Infer timestamps > 0 & face_valid for legacy archives
            n_w, n_f = feats.shape[0], feats.shape[1]
            vm = np.ones((n_w, n_f), dtype=bool)
            if "face_valid" in fnames:
                fv_idx = fnames.index("face_valid")
                vm = vm & (feats[:, :, fv_idx] > 0.5)
            if "timestamps" in data:
                ts = data["timestamps"]
                if ts.shape == (n_w, n_f) and np.any(ts > 0):
                    vm = vm & (ts > 0)
            elif "timestamp" in fnames:
                ts_idx = fnames.index("timestamp")
                if np.any(feats[:, :, ts_idx] > 0):
                    vm = vm & (feats[:, :, ts_idx] > 0)

        raw_archives.append({
            "features": feats,
            "subject_ids": subs,
            "labels": labs,
            "feature_names": fnames,
            "valid_masks": vm,
        })
        for fn in fnames:
            if fn not in target_feature_names:
                target_feature_names.append(fn)

    if not raw_archives:
        raise ValueError("No valid .npz data files found to load.")

    # Determine canonical window frame count along temporal axis 1
    frame_counts = [
        arc["features"].shape[1]
        for arc in raw_archives
        if arc["features"].ndim == 3 and arc["features"].shape[0] > 0
    ]
    if target_frames is None:
        if not frame_counts:
            target_frames = 90
        elif len(set(frame_counts)) == 1:
            target_frames = frame_counts[0]
        else:
            if 90 in frame_counts:
                target_frames = 90
            else:
                from collections import Counter
                target_frames = Counter(frame_counts).most_common(1)[0][0]

    all_features = []
    all_valid_masks = []
    all_subjects = []
    all_labels = []
    n_target_features = len(target_feature_names)

    for arc in raw_archives:
        feats = arc["features"]
        fnames = arc["feature_names"]
        subs = arc["subject_ids"]
        labs = arc["labels"]
        vm = arc["valid_masks"]

        if feats.ndim != 3 or feats.shape[0] == 0:
            continue

        n_win, win_frames, _ = feats.shape

        # 1. Feature channel alignment across schemas
        if fnames == target_feature_names:
            aligned_feats = feats
        else:
            aligned_feats = np.zeros((n_win, win_frames, n_target_features), dtype=np.float32)
            fname_to_idx = {fn: idx for idx, fn in enumerate(fnames)}
            for t_idx, t_name in enumerate(target_feature_names):
                if t_name in fname_to_idx:
                    aligned_feats[:, :, t_idx] = feats[:, :, fname_to_idx[t_name]]

        # 2. Temporal frame count alignment along axis 1 (if framerate differs)
        if win_frames != target_frames:
            if win_frames <= 1:
                aligned_feats = np.repeat(aligned_feats, target_frames, axis=1)
                aligned_vm = np.repeat(vm, target_frames, axis=1)
            else:
                from scipy.interpolate import interp1d
                x_orig = np.linspace(0.0, 1.0, win_frames)
                x_target = np.linspace(0.0, 1.0, target_frames)
                resampled = interp1d(
                    x_orig, aligned_feats, axis=1, kind="linear", assume_sorted=True
                )(x_target).astype(np.float32)

                from pipeline.training_buffer import TrainingBuffer
                bool_names = set(TrainingBuffer.CORE_BOOL_NAMES + TrainingBuffer.EXTENDED_BOOL_NAMES)
                for t_idx, t_name in enumerate(target_feature_names):
                    if t_name in bool_names:
                        resampled[:, :, t_idx] = (resampled[:, :, t_idx] >= 0.5).astype(np.float32)

                aligned_feats = resampled
                aligned_vm = interp1d(
                    x_orig, vm.astype(np.float32), axis=1, kind="nearest", assume_sorted=True, fill_value="extrapolate"
                )(x_target) >= 0.5
        else:
            aligned_vm = vm

        valid_win_mask = np.any(aligned_vm, axis=1)
        if not np.all(valid_win_mask):
            n_dropped = int(np.sum(~valid_win_mask))
            print(f"[Dataset Quarantine] Dropped {n_dropped} completely invalid/all-gated windows.")
            aligned_feats = aligned_feats[valid_win_mask]
            aligned_vm = aligned_vm[valid_win_mask]
            subs = subs[valid_win_mask]
            labs = labs[valid_win_mask]
        if len(aligned_feats) == 0:
            continue

        all_features.append(aligned_feats)
        all_valid_masks.append(aligned_vm)
        all_subjects.append(subs)
        all_labels.append(labs)

    if not all_features:
        raise ValueError("No valid window samples found across all archives.")

    X_3d = np.concatenate(all_features, axis=0)
    valid_masks_out = np.concatenate(all_valid_masks, axis=0).astype(bool)
    subjects = np.concatenate(all_subjects, axis=0)
    raw_labels = np.concatenate(all_labels, axis=0)

    # Convert labels to binary integers (0 = Sober, 1 = Impaired)
    y = np.zeros(len(raw_labels), dtype=np.int32)
    for i, lbl in enumerate(raw_labels):
        clean_lbl = str(lbl).strip().lower()
        if clean_lbl in LABEL_IMPAIRED_ALIASES:
            y[i] = 1
        else:
            y[i] = 0

    if return_valid_masks:
        return X_3d, y, subjects, target_feature_names, valid_masks_out
    return X_3d, y, subjects, target_feature_names


